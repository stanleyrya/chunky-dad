#!/usr/bin/env node
// Generates js/event-plates.data.js — the favicon plate colour for each event
// website domain, so the homepage's bear-run icons can sit on their own plate
// the way the city-page markers already do.
//
// tools/extract-favicon-colors.js writes faviconPlate per event into
// data/event-colors/<city>.json. Those files are keyed by event slug; the
// homepage only knows a card's website, and its favicon file is already named
// by domain (img/favicons/favicon-<domain>-64px.ico), so domain is the key
// that both sides share.
//
// CI refreshes this in update-calendar-data.yml right after the colours are
// extracted. A domain with no entry simply falls back to the white plate.
const fs = require('fs');
const path = require('path');

function hostOf(url) {
    try {
        return new URL(url).hostname.replace(/^www\./, '').toLowerCase();
    } catch (e) {
        return null;
    }
}

// Pure: entries = [{url, faviconPlate}, ...] from every colour file
function buildPlateIndex(entries) {
    const domains = {};
    for (const entry of entries || []) {
        if (!entry || !entry.url || !entry.faviconPlate) continue;
        if (!/^#[0-9a-fA-F]{3,8}$/.test(entry.faviconPlate)) continue;
        const host = hostOf(entry.url);
        if (!host || domains[host]) continue;   // first writer wins, stable across runs
        domains[host] = entry.faviconPlate.toLowerCase();
    }
    return domains;
}

function render(domains, generatedAt) {
    return `// GENERATED by tools/generate-event-plates.js — do not edit by hand.\n` +
        `// faviconPlate per event-website domain; the homepage reads it to tint\n` +
        `// each bear-run icon's plate (see js/compact-card-renderer.js).\n` +
        `window.EVENT_PLATES = ${JSON.stringify({ generatedAt, domains }, null, 1)};\n`;
}

function main() {
    const root = path.join(__dirname, '..');
    const dir = path.join(root, 'data', 'event-colors');
    if (!fs.existsSync(dir)) {
        console.log('No data/event-colors directory — nothing to do.');
        return;
    }
    const entries = [];
    for (const file of fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort()) {
        try {
            const parsed = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
            if (Array.isArray(parsed)) entries.push(...parsed);
        } catch (e) {
            console.warn(`⚠️  ${file} unreadable: ${e.message}`);
        }
    }
    const domains = buildPlateIndex(entries);
    const today = new Date().toISOString().slice(0, 10);
    const out = path.join(root, 'js', 'event-plates.data.js');
    fs.writeFileSync(out, render(domains, today));
    const tinted = Object.values(domains).filter(v => v !== '#ffffff').length;
    console.log(`✅ ${path.relative(root, out)}: ${Object.keys(domains).length} domains, ${tinted} with a colour other than white`);
}

if (require.main === module) main();

module.exports = { buildPlateIndex, hostOf, render };
