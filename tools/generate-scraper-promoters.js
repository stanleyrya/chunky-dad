#!/usr/bin/env node

// Generates scripts/scraper-promoters.js (the environment-agnostic JS twin of
// data/promoters.json) — sibling of tools/generate-scraper-bars.js. The JSON
// file is canonical: the deployed site serves it at
// https://chunky.dad/data/promoters.json for the scraper's remote refresh,
// and this twin is what the local/offline adapters load.

const fs = require('fs');
const path = require('path');

// Resolve project root relative to this script
const ROOT = path.resolve(__dirname, '..');

// Pure source builder — exported so the registry test can verify the committed
// twin is in sync without executing the writer.
function buildScraperPromotersSource(promoters) {
  const header = [
    '// Bear Event Scraper Promoters Configuration',
    '// This file is generated by tools/generate-scraper-promoters.js from data/promoters.json.',
    '// Do not edit this file directly.',
    '//',
    '// USAGE RESTRICTIONS:',
    '// - This is a pure JavaScript configuration file',
    '// - Must export a default promoters configuration array',
    '// - Can be imported in both Scriptable and web environments',
    '// - Keep this file environment-agnostic (no Scriptable or DOM APIs)',
    ''
  ].join('\n');

  const exportBlock = [
    '// Export for different environments',
    '// Scriptable environment',
    "if (typeof module !== 'undefined' && module.exports) {",
    '  module.exports = scraperPromoters;',
    '}',
    '',
    '// ES6 module environment',
    "if (typeof window === 'undefined' && typeof importModule !== 'undefined') {",
    '  // Scriptable environment - make available for importModule',
    '  scraperPromoters;',
    "} else if (typeof window !== 'undefined') {",
    '  // Browser environment - attach to window',
    '  window.scraperPromoters = scraperPromoters;',
    '}',
    '',
    '// Default export for ES6 modules',
    'scraperPromoters;',
    ''
  ].join('\n');

  return `${header}const scraperPromoters = ${JSON.stringify(promoters, null, 2)};\n\n${exportBlock}`;
}

// Write only if content changes
function writeIfChanged(filePath, content) {
  if (fs.existsSync(filePath)) {
    const existing = fs.readFileSync(filePath, 'utf8');
    if (existing === content) {
      return false;
    }
  }
  fs.writeFileSync(filePath, content);
  return true;
}

function main() {
  const promotersPath = path.join(ROOT, 'data', 'promoters.json');
  if (!fs.existsSync(promotersPath)) {
    console.error(`Promoters file not found: ${promotersPath}`);
    process.exit(1);
  }

  let promoters;
  try {
    promoters = JSON.parse(fs.readFileSync(promotersPath, 'utf8'));
  } catch (e) {
    console.error(`Failed to parse ${promotersPath}:`, e.message);
    process.exit(1);
  }

  if (!Array.isArray(promoters) || promoters.length === 0) {
    console.error('No promoter data found to generate scraper-promoters.js');
    process.exit(1);
  }

  const outputPath = path.join(ROOT, 'scripts', 'scraper-promoters.js');
  const changed = writeIfChanged(outputPath, buildScraperPromotersSource(promoters));

  if (changed) {
    console.log(`✓ Wrote ${path.relative(ROOT, outputPath)}`);
  } else {
    console.log(`⏭️  No change for ${path.relative(ROOT, outputPath)}`);
  }
}

if (require.main === module) {
  main();
}

module.exports = { buildScraperPromotersSource };
