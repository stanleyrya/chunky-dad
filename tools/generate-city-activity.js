#!/usr/bin/env node
// Generates js/city-activity.data.js — a per-city summary of what the
// calendars hold, so the site can delist cities that have nothing coming up
// WITHOUT anyone hand-editing `visible` in js/city-config.js.
//
// The browser (getAvailableCities in js/city-config.js) makes the "is this
// city active?" call at page-load time from the dates written here, so the
// file only needs regenerating when the calendars change — CI does that in
// update-calendar-data.yml. Past dates left in the list are harmless.
//
// `visible: false` in city-config stays the manual, hard delist (no calendar
// at all, or "don't show this yet"); this file only ever hides cities that
// have a calendar and nothing on it.
const fs = require('fs');
const path = require('path');

const MAX_DATES = 120;

function isoDate(d) {
    const y = d.getFullYear();
    const m = String(d.getMonth() + 1).padStart(2, '0');
    const day = String(d.getDate()).padStart(2, '0');
    return `${y}-${m}-${day}`;
}

function rruleUntil(rrule) {
    const m = /UNTIL=(\d{4})(\d{2})(\d{2})/.exec(rrule || '');
    return m ? `${m[1]}-${m[2]}-${m[3]}` : null;
}

// Pure: { cityConfig, calendars: { key -> parsed <key>.json }, festivals: [...], today: 'YYYY-MM-DD' }
function computeCityActivity({ cityConfig, calendars, festivals, today }) {
    const cities = {};
    const festivalList = Array.isArray(festivals) ? festivals : (festivals && festivals.festivals) || [];

    for (const key of Object.keys(cityConfig || {})) {
        const cal = calendars[key];
        if (!cal || !Array.isArray(cal.events)) continue; // nothing to judge by → not listed → shown

        const dates = new Set();
        let recurring = 0;
        for (const ev of cal.events) {
            const start = typeof ev.startDate === 'string' ? ev.startDate.slice(0, 10) : null;
            if (ev.recurring && ev.recurrence) {
                const until = rruleUntil(ev.recurrence);
                if (!until || until >= today) recurring++;
                continue;
            }
            if (start && start >= today) dates.add(start);
        }

        let festivalUntil = null;
        for (const f of festivalList) {
            if (f.cityKey !== key || !f.nextDates) continue;
            const end = f.nextDates.end || f.nextDates.start;
            if (end && end >= today && (!festivalUntil || end > festivalUntil)) festivalUntil = end;
        }

        cities[key] = {
            dates: Array.from(dates).sort().slice(0, MAX_DATES),
            recurring,
            festivalUntil
        };
    }
    return cities;
}

function isActive(entry, today) {
    if (!entry) return true;
    if (entry.recurring > 0) return true;
    if (entry.festivalUntil && entry.festivalUntil >= today) return true;
    return (entry.dates || []).some(d => d >= today);
}

function render(cities, generatedAt) {
    return `// GENERATED by tools/generate-city-activity.js — do not edit by hand.\n` +
        `// Per-city calendar summary; js/city-config.js reads it to delist cities\n` +
        `// with nothing upcoming (see isCityActive there).\n` +
        `window.CITY_ACTIVITY = ${JSON.stringify({ generatedAt, cities }, null, 1)};\n`;
}

function main() {
    const root = path.join(__dirname, '..');
    const { CITY_CONFIG } = require(path.join(root, 'js', 'city-config.js'));
    const calDir = path.join(root, 'data', 'calendars');
    const calendars = {};
    for (const key of Object.keys(CITY_CONFIG)) {
        const p = path.join(calDir, `${key}.json`);
        if (fs.existsSync(p)) {
            try { calendars[key] = JSON.parse(fs.readFileSync(p, 'utf8')); }
            catch (e) { console.warn(`⚠️  ${key}.json unreadable: ${e.message}`); }
        }
    }
    let festivals = [];
    const festPath = path.join(root, 'data', 'festivals.json');
    if (fs.existsSync(festPath)) festivals = JSON.parse(fs.readFileSync(festPath, 'utf8'));

    const today = isoDate(new Date());
    const cities = computeCityActivity({ cityConfig: CITY_CONFIG, calendars, festivals, today });
    const out = path.join(root, 'js', 'city-activity.data.js');
    fs.writeFileSync(out, render(cities, today));

    const listed = Object.keys(cities);
    const quiet = listed.filter(k => !isActive(cities[k], today));
    console.log(`✅ ${path.relative(root, out)}: ${listed.length} cities summarised, ${quiet.length} with nothing upcoming` +
        (quiet.length ? ` (${quiet.join(', ')})` : ''));
}

if (require.main === module) main();

module.exports = { computeCityActivity, isActive, rruleUntil, render };
